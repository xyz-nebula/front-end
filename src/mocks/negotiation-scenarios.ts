export function getNegotiationScenario(caseId: string): NegotiationScenario {
  return negotiationScenarios[caseId] ?? fallbackScenario
}

export function getMockAiResponse(caseId: string, turnNumber: number): string {
  const responses = getNegotiationScenario(caseId).aiResponses
  return responses[(Math.max(1, turnNumber) - 1) % responses.length]
}
