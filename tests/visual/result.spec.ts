import { artifactsDir, captureScreenshot, expect, expectNoHorizontalOverflow, test } from './helpers'

test('result polls processing, shows analysis and repeats case as a new session', async ({ page }) => {
  test.skip(process.env.VITE_AUTH_SOURCE !== 'mock' || process.env.VITE_NEGOTIATION_SOURCE !== 'mock', 'Requires full mock mode.')
  test.setTimeout(50_000)
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/register')
  await page.getByLabel('Имя', { exact: true }).fill('Иван')
  await page.getByLabel('Фамилия').fill('Сидоров')
  await page.getByLabel('Email').fill('result@example.com')
  await page.getByLabel('Пароль').fill('strong-password')
  await page.getByRole('button', { name: 'Создать аккаунт' }).click()
  await page.getByRole('link', { name: 'Открыть demo-ссылку активации' }).click()
  await page.getByRole('link', { name: 'Перейти в приложение' }).click()
  await page.getByRole('button', { name: 'Начать кейс' }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('radio', { name: /Сотрудник/ }).check()
  await dialog.getByRole('button', { name: 'Начать подготовку' }).click()
  await expect(page).toHaveURL(/\/cases\/salary-review\/preparation/)
  await page.getByRole('button', { name: 'Начать поединок' }).first().click()
  await expect(page).toHaveURL(/\/arena\/[0-9a-f-]+$/)
  await page.getByLabel('Ваша реплика').fill('Какие результаты помогут нам договориться о новых условиях?')
  await page.locator('.arena-composer').getByRole('button').click()
  await expect(page.locator('.arena-message')).toHaveCount(2)
  await page.getByLabel('Ваша реплика').fill('Давайте зафиксируем критерии и срок следующего шага.')
  await page.locator('.arena-composer').getByRole('button').click()
  await expect(page.locator('.arena-message')).toHaveCount(4)
  const originalId = page.url().split('/').at(-1)
  await page.getByRole('button', { name: 'Завершить' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Завершить' }).click()
  await expect(page).toHaveURL(/\/result\/[0-9a-f-]+$/)
  await expect(page.getByRole('heading', { name: 'Анализируем разговор…' })).toBeVisible()
  await captureScreenshot(page, `${artifactsDir}/result-processing-desktop.png`)
  await expect(page.getByRole('heading', { name: 'Разбор поединка' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Договорённость достигнута' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Что решили судьи' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Разбор тренера' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Упущенные возможности' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Цель достигнута' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'План vs реальность' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Что попробовать в следующей попытке' })).toBeVisible()
  await expectNoHorizontalOverflow(page)
  await captureScreenshot(page, `${artifactsDir}/result-ready-desktop.png`, true)
  await page.setViewportSize({ width: 390, height: 844 })
  await expectNoHorizontalOverflow(page)
  await captureScreenshot(page, `${artifactsDir}/result-ready-mobile.png`, true)
  await page.getByText('Полный транскрипт').click()
  const transcript = page.locator('.result-transcript')
  await expect(transcript.getByText('Какие результаты помогут нам договориться о новых условиях?', { exact: true })).toBeVisible()
  await expect(transcript.getByText('Давайте зафиксируем критерии и срок следующего шага.', { exact: true })).toBeVisible()
  await page.getByText('Полный транскрипт').click()
  await page.getByRole('button', { name: 'Повторить кейс' }).click()
  await expect(page).toHaveURL(/\/arena\/[0-9a-f-]+$/)
  expect(page.url().split('/').at(-1)).not.toBe(originalId)
  await expect(page.getByRole('heading', { name: 'Начните разговор' })).toBeVisible()
  await page.getByRole('button', { name: 'Завершить' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Завершить' }).click()
  await expect(page).toHaveURL(/\/result\/[0-9a-f-]+$/)
  await expect(page.getByRole('heading', { name: 'Договорённость не достигнута' })).toBeVisible()
})

test('result error keeps retry and home actions available', async ({ page }) => {
  test.skip(process.env.VITE_AUTH_SOURCE !== 'mock' || process.env.VITE_NEGOTIATION_SOURCE !== 'mock', 'Requires full mock mode.')
  await page.goto('/register')
  await page.getByLabel('Имя', { exact: true }).fill('Анна')
  await page.getByLabel('Фамилия').fill('Иванова')
  await page.getByLabel('Email').fill('result-error@example.com')
  await page.getByLabel('Пароль').fill('strong-password')
  await page.getByRole('button', { name: 'Создать аккаунт' }).click()
  await page.getByRole('link', { name: 'Открыть demo-ссылку активации' }).click()
  await page.getByRole('link', { name: 'Перейти в приложение' }).click()
  await page.goto('/result/missing-session')
  await expect(page.getByRole('heading', { name: 'Не удалось получить разбор' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Проверить ещё раз' })).toBeVisible()
  await expect(page.getByRole('link', { name: 'К кейсам' })).toBeVisible()
  await expectNoHorizontalOverflow(page)
})
